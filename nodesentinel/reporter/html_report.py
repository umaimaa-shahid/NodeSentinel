
import html
from datetime import datetime, timezone


def generate_html_report(target, findings):
    severity_counts = {}

    for finding in findings:
        severity = finding.get("severity", "Informational")
        severity_counts[severity] = severity_counts.get(severity, 0) + 1

    severity_summary = ""

    for severity in [
        "Critical",
        "High",
        "Medium",
        "Low",
        "Informational",
    ]:
        count = severity_counts.get(severity, 0)

        severity_summary += f"""
        <div class="summary-card">
            <h3>{html.escape(severity)}</h3>
            <p>{count}</p>
        </div>
        """

    findings_html = ""

    if not findings:
        findings_html = """
        <p class="no-findings">No security findings detected.</p>
        """

    for finding in findings:
        finding_id = html.escape(str(finding.get("id", "N/A")))
        title = html.escape(str(finding.get("title", "Untitled Finding")))
        severity = html.escape(str(finding.get("severity", "Informational")))
        category = html.escape(str(finding.get("category", "General")))
        description = html.escape(str(finding.get("description", "No description provided.")))
        recommendation = html.escape(str(finding.get("recommendation", "No recommendation provided.")))

        findings_html += f"""
        <div class="finding">
            <h3>{title}</h3>
            <p><strong>ID:</strong> {finding_id}</p>
            <p><strong>Severity:</strong>
                <span class="severity">{severity}</span>
            </p>
            <p><strong>Category:</strong> {category}</p>
            <p><strong>Description:</strong> {description}</p>
            <p><strong>Recommendation:</strong> {recommendation}</p>
        </div>
        """

    safe_target = html.escape(str(target))
    scan_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>NodeSentinel Security Report</title>

    <style>
        body {{
            font-family: Arial, sans-serif;
            background: #f4f6f9;
            color: #222;
            margin: 0;
            padding: 30px;
        }}

        .container {{
            max-width: 1000px;
            margin: auto;
        }}

        h1 {{
            color: #16324f;
        }}

        .info {{
            background: white;
            padding: 20px;
            border-radius: 8px;
            margin-bottom: 25px;
        }}

        .summary {{
            display: flex;
            flex-wrap: wrap;
            gap: 15px;
            margin-bottom: 25px;
        }}

        .summary-card {{
            background: white;
            padding: 15px;
            border-radius: 8px;
            flex: 1;
            min-width: 120px;
            text-align: center;
        }}

        .summary-card p {{
            font-size: 24px;
            font-weight: bold;
        }}

        .finding {{
            background: white;
            padding: 20px;
            border-radius: 8px;
            margin-bottom: 15px;
            border-left: 5px solid #d97706;
            overflow-wrap: anywhere;
        }}

        .finding h3 {{
            color: #16324f;
        }}

        .severity {{
            font-weight: bold;
        }}

        .no-findings {{
            background: white;
            padding: 20px;
            border-radius: 8px;
        }}

        footer {{
            margin-top: 30px;
            color: #666;
            font-size: 13px;
        }}
    </style>
</head>

<body>
    <div class="container">

        <h1>NodeSentinel Security Report</h1>

        <div class="info">
            <p><strong>Target:</strong> {safe_target}</p>
            <p><strong>Scan time:</strong> {scan_time}</p>
            <p><strong>Total findings:</strong> {len(findings)}</p>
        </div>

        <h2>Severity Summary</h2>

        <div class="summary">
            {severity_summary}
        </div>

        <h2>Security Findings</h2>

        {findings_html}

        <footer>
            Generated by NodeSentinel.
        </footer>

    </div>
</body>
</html>
"""


def write_html_report(target, findings, output_path):
    html_content = generate_html_report(target, findings)

    with open(output_path, "w", encoding="utf-8") as file:
        file.write(html_content)

    return output_path
